#!/usr/bin/env python3
"""Generate 02_codes.sql (code lookup tables + seed rows) from the Vervent data
dictionary workbook.

    python3 sql/generate_codes.py [path/to/Vervent Data Dictionary.xlsx]

Requires openpyxl. The output is idempotent (ON CONFLICT DO NOTHING keeps
local edits to descriptions; delete the rows first to re-seed).
"""
from __future__ import annotations

import os
import sys
from collections import OrderedDict

import openpyxl

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_XLSX = os.path.join(
    HERE, "..", "backlog", "collections", "Vervent Data Dictionary - Updated 06.04.26.xlsx"
)

# sheet name -> (code_set, column indexes: code, description, definition|None, header rows to skip)
CODE_SHEETS = [
    ("Status (LS Status)", "ls_status", 0, 1, None, 1),
    ("Asset Status", "asset_status", 0, 1, 2, 1),
    ("LS Type", "ls_type", 0, 1, None, 1),
    ("Accrual Method", "accrual_method", 0, 1, 2, 1),
    ("Late Code", "late_code", 0, 1, None, 1),
    ("Use Tax Code", "use_tax_code", 0, 1, None, 1),
    ("LS Source", "ls_source", 0, 1, None, 1),
    ("Coll Code", "coll_code", 0, 1, None, 1),
    ("Repo Code", "repo_code", 0, 1, None, 1),
    ("Bank Codes", "bank_code", 0, 1, 2, 1),
    ("Tran Code", "tran_code", 0, 1, 2, 1),
]
GL_SHEET = "GL Codes_Vectors"

CODE_SET_DOC = {
    "ls_status": "contract_summary.ls_status, asset_summary.contr_status",
    "asset_status": "asset_summary.status",
    "ls_type": "contract_summary.ls_type, asset_summary.ls_type",
    "accrual_method": "contract_summary.accrual_method",
    "late_code": "contract_summary.late_code",
    "use_tax_code": "contract_summary.use_tax_code, asset_summary.tax_code",
    "ls_source": "contract_summary.ls_source",
    "coll_code": "contract_summary.coll_code",
    "repo_code": "asset_summary.curr_repo_status, asset_summary.repo_code",
    "bank_code": "transaction_history.bankcd",
    "tran_code": "transaction_history.trans",
}


def clean(v) -> str | None:
    if v is None:
        return None
    s = str(v).replace("’", "'").strip()
    return s or None


def sql_str(s: str | None) -> str:
    return "NULL" if s is None else "'" + s.replace("'", "''") + "'"


def read_sheet(wb, name, skip):
    ws = wb[name]
    rows = list(ws.iter_rows(values_only=True))[skip:]
    return [r for r in rows if any(clean(v) for v in r)]


def collect_codes(wb):
    """-> OrderedDict[(code_set, code)] = [description, definition]"""
    out: "OrderedDict[tuple, list]" = OrderedDict()
    for sheet, code_set, ci, di, fi, skip in CODE_SHEETS:
        for row in read_sheet(wb, sheet, skip):
            code = clean(row[ci]) if ci < len(row) else None
            if not code:
                continue
            desc = clean(row[di]) if di < len(row) else None
            defn = clean(row[fi]) if fi is not None and fi < len(row) else None
            # "NLSE/ULSE" + "NEW/USED ON LEASE" style combined rows -> one row
            # per code, with the matching half of the description
            parts = [p.strip() for p in code.split("/") if p.strip()]
            for n, c in enumerate(parts):
                d = desc
                if len(parts) == 2 and desc and desc.upper().startswith("NEW/USED "):
                    d = ("NEW" if n == 0 else "USED") + desc[len("NEW/USED"):]
                key = (code_set, c)
                if key in out:
                    # repeated code (Repo Code sheet): merge distinct descriptions
                    for i, v in enumerate((d, defn)):
                        if v and v.lower() != (out[key][i] or "").lower():
                            out[key][i] = f"{out[key][i]} / {v}" if out[key][i] else v
                else:
                    out[key] = [d, defn]
    return out


def collect_gl(wb):
    rows = []
    for row in read_sheet(wb, GL_SHEET, 1):
        vec = clean(row[0])
        if vec is None:
            continue
        try:
            vec_i = int(float(vec))
        except ValueError:
            continue
        rows.append((vec_i, clean(row[1]) if len(row) > 1 else None, clean(row[2]) if len(row) > 2 else None))
    return rows


def main() -> None:
    xlsx = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_XLSX
    wb = openpyxl.load_workbook(xlsx, read_only=True, data_only=True)
    codes = collect_codes(wb)
    gl = collect_gl(wb)

    lines = [
        "-- =============================================================================",
        "-- Vervent code lookups, seeded from the Vervent data dictionary workbook.",
        "-- GENERATED by generate_codes.py — regenerate rather than editing by hand.",
        f"-- Source: {os.path.basename(xlsx)}",
        "-- Idempotent: psql -v ON_ERROR_STOP=1 -f 02_codes.sql (after 01_schema.sql)",
        "-- =============================================================================",
        "",
        "CREATE TABLE IF NOT EXISTS vervent.code_values (",
        "  code_set    text NOT NULL,",
        "  code        text NOT NULL,",
        "  description text,",
        "  definition  text,",
        "  PRIMARY KEY (code_set, code)",
        ");",
        "COMMENT ON TABLE vervent.code_values IS 'Vervent/LeasePak code descriptions. Join with LEFT JOIN on (code_set, code); report tables carry codes the dictionary does not list.';",
        "COMMENT ON COLUMN vervent.code_values.code_set IS 'One of: "
        + "; ".join(f"{k} ({v})" for k, v in CODE_SET_DOC.items())
        + "';",
        "",
        "CREATE TABLE IF NOT EXISTS vervent.gl_vector (",
        "  vector      integer PRIMARY KEY,",
        "  gl_account  text,",
        "  description text",
        ");",
        "COMMENT ON TABLE vervent.gl_vector IS 'General-ledger vectors referenced by transaction_history.debit_vector / credit_vector.';",
        "",
        "INSERT INTO vervent.code_values (code_set, code, description, definition) VALUES",
    ]
    vals = [
        f"  ({sql_str(cs)}, {sql_str(code)}, {sql_str(d)}, {sql_str(f)})"
        for (cs, code), (d, f) in codes.items()
    ]
    lines.append(",\n".join(vals))
    lines.append("ON CONFLICT (code_set, code) DO NOTHING;")
    lines.append("")
    lines.append("INSERT INTO vervent.gl_vector (vector, gl_account, description) VALUES")
    lines.append(",\n".join(f"  ({v}, {sql_str(a)}, {sql_str(d)})" for v, a, d in gl))
    lines.append("ON CONFLICT (vector) DO NOTHING;")
    lines.append("")

    out = os.path.join(HERE, "02_codes.sql")
    with open(out, "w") as f:
        f.write("\n".join(lines))
    by_set = {}
    for cs, _ in codes:
        by_set[cs] = by_set.get(cs, 0) + 1
    print(f"wrote {out}: {len(codes)} codes", by_set, f"+ {len(gl)} GL vectors")


if __name__ == "__main__":
    main()
