#!/usr/bin/env python3
"""Generate SQL load scripts for the Camber Credit 2026-1 lease tape.

Reads the distribution xlsx and emits multi-row INSERT scripts for the
entities defined in 01_schema.sql. Rerunnable: output files are overwritten.

Usage: python3 generate_loads.py [path-to-xlsx]
"""
import sys
from pathlib import Path

import openpyxl

HERE = Path(__file__).resolve().parent
DEFAULT_XLSX = HERE.parent / "Camber Credit 2026-1 - Lease Tape August 2026 (Final - For Distribution).xlsx"
SNAPSHOT_DATE = "2026-08-31"
PRIOR_VALUATION_DATE = "2025-10-31"
DISCOUNT_RATE = "0.0900"
BATCH = 500


def q(s):
    """SQL-quote a string literal (PostgreSQL standard-conforming strings)."""
    return "'" + str(s).replace("'", "''") + "'"


def num(v, places):
    if v is None or v == "":
        return "NULL"
    return f"{round(float(v), places):.{places}f}"


def opt_str(v):
    return q(v) if v not in (None, "") else "NULL"


def write_inserts(path, header_comment, table, columns, rows):
    with open(path, "w") as f:
        f.write(f"-- {header_comment}\n-- Generated by generate_loads.py — do not edit by hand.\n")
        f.write("SET search_path TO camber_credit;\n\n")
        for i in range(0, len(rows), BATCH):
            f.write(f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n")
            f.write(",\n".join("  (" + ", ".join(r) + ")" for r in rows[i : i + BATCH]))
            f.write(";\n\n")
    print(f"wrote {path.name}: {len(rows)} rows")


def main():
    xlsx = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_XLSX
    wb = openpyxl.load_workbook(xlsx, read_only=True, data_only=True)
    ws = wb["CC 2026-1"]
    rows = list(ws.iter_rows(values_only=True))
    data = [r for r in rows[2:] if r[0] is not None]  # row 0 = control totals, row 1 = header
    assert len({r[0] for r in data}) == len(data), "idx not unique"
    assert len({r[1] for r in data}) == len(data), "vin not unique"

    vehicles, leases, snapshots, valuations = [], [], [], []
    for r in data:
        (idx, vin, year, ymm, fuel, new_used, oc, bp, ext, term, ldate, mdate,
         cost, resid, pmt, alg, dcf, pv_prior, status, term_type, term_cat,
         sold_month, proceeds, aug_pmt, days_del, n_rem, pv_resid, pv_total,
         eligible, pv_elig) = r

        vehicles.append([q(vin), str(year), q(ymm), q(fuel)])
        leases.append([
            str(idx), q(vin), q(new_used), q(oc), q(bp),
            "TRUE" if ext == "True" else "FALSE", str(term),
            q(ldate.date()), q(mdate.date()),
            num(cost, 2), num(resid, 2), num(pmt, 2), q(alg), num(dcf, 9),
        ])
        snapshots.append([
            str(idx), q(SNAPSHOT_DATE), str(status),
            opt_str(term_type), opt_str(term_cat), opt_str(sold_month),
            num(proceeds, 2) if proceeds not in (None, "") else "NULL",
            num(aug_pmt, 2), str(days_del), str(n_rem),
            "TRUE" if eligible == 1 else "FALSE",
        ])
        valuations.append([str(idx), q(PRIOR_VALUATION_DATE), DISCOUNT_RATE,
                           num(pv_prior, 6), "NULL", "NULL"])
        valuations.append([str(idx), q(SNAPSHOT_DATE), DISCOUNT_RATE,
                           num(pv_total, 6), num(pv_resid, 6), num(pv_elig, 6)])

    write_inserts(HERE / "03_load_vehicles.sql",
                  "Camber Credit 2026-1 — vehicles", "vehicles",
                  ["vin", "model_year", "description", "fuel_type"], vehicles)
    write_inserts(HERE / "04_load_leases.sql",
                  "Camber Credit 2026-1 — leases", "leases",
                  ["lease_id", "vin", "new_used", "open_closed", "obligor_type",
                   "is_extended", "lease_term_months", "lease_date", "maturity_date",
                   "orig_cost", "contract_residual_value", "payment_regular",
                   "alg_model_used", "lease_dcf"], leases)
    write_inserts(HERE / "05_load_lease_snapshots.sql",
                  f"Camber Credit 2026-1 — servicing snapshot as of {SNAPSHOT_DATE}",
                  "lease_snapshots",
                  ["lease_id", "asof_date", "status_code", "termination_type",
                   "termination_timing_category", "sold_month", "net_sales_proceeds",
                   "period_payment_collected", "days_delinquent", "payments_remaining",
                   "is_eligible_collateral"], snapshots)
    write_inserts(HERE / "06_load_lease_valuations.sql",
                  f"Camber Credit 2026-1 — 9% DCF par values as of {PRIOR_VALUATION_DATE} and {SNAPSHOT_DATE}",
                  "lease_valuations",
                  ["lease_id", "asof_date", "discount_rate", "pv_total",
                   "pv_contract_residual", "pv_eligible_collateral"], valuations)


if __name__ == "__main__":
    main()
